import fs from "node:fs"
import path from "node:path"
import type { Plugin } from "vite"

/**
 * Full set of top-level fields exposed by `world-countries@5`.
 * Keep this in sync with the upstream JSON schema; the plugin will throw if
 * the user (or auto-detection) requests something outside this whitelist so
 * that typos surface at build time instead of producing silent `undefined`s.
 */
export const WORLD_COUNTRIES_FIELDS = [
  "altSpellings",
  "area",
  "borders",
  "capital",
  "cca2",
  "cca3",
  "ccn3",
  "cioc",
  "currencies",
  "demonyms",
  "flag",
  "idd",
  "independent",
  "landlocked",
  "languages",
  "latlng",
  "name",
  "region",
  "status",
  "subregion",
  "tld",
  "translations",
  "unMember",
  "unRegionalGroup",
] as const

export type WorldCountriesField = (typeof WORLD_COUNTRIES_FIELDS)[number]

export interface WorldCountriesFilterOptions {
  /**
   * - `"auto"`: scan project sources for member access on the imported binding
   *   and keep only the referenced fields. Cheapest to maintain — add a new
   *   `c.region` reference and the field will start being included on next
   *   build.
   * - `"manual"`: use the explicit `fields` list verbatim.
   * - `"merge"` (default): union of `auto` + `fields`. Use `fields` to force-
   *   include something the scanner can't see (dynamic key, JSON.stringify,
   *   re-export, etc.) without losing the auto-detection convenience.
   */
  mode?: "auto" | "manual" | "merge"

  /**
   * Explicit fields to keep. Required when `mode === "manual"`, optional in
   * the other two modes (treated as additions in `merge`).
   */
  fields?: WorldCountriesField[]

  /**
   * Globs (relative to project root) that the auto-scanner walks. Defaults to
   * the `src/` tree; broaden it if you import `world-countries` from elsewhere
   * (e.g. a `scripts/` build helper that ends up bundled).
   */
  include?: string[]

  /**
   * Print the resolved field list during build. Helpful when wiring this up
   * for the first time. Defaults to `true` so it's obvious what's shipping.
   */
  verbose?: boolean

  /**
   * Override the path to the upstream `countries.json`. The plugin resolves it
   * via `import.meta.resolve`-equivalent lookup by default, so you only need
   * this for pnpm workspaces with non-standard hoisting.
   */
  countriesJsonPath?: string
}

const VIRTUAL_ID = "\0virtual:world-countries-filtered"
const REAL_SPECIFIER = "world-countries"

/**
 * Vite plugin that swaps `import countries from 'world-countries'` for a
 * field-pruned virtual module. Cuts ~125 kB gzipped from the chunk that
 * imports it without changing any runtime call sites.
 */
export function worldCountriesFilter(
  options: WorldCountriesFilterOptions = {},
): Plugin {
  const {
    mode = "merge",
    fields: manualFields = [],
    include = ["src/**/*.{ts,tsx,js,jsx,mjs,cjs}"],
    verbose = true,
    countriesJsonPath,
  } = options

  if (mode === "manual" && manualFields.length === 0) {
    throw new Error(
      "[world-countries-filter] mode=\"manual\" requires a non-empty `fields` array.",
    )
  }

  validateFields(manualFields)

  let projectRoot = process.cwd()
  let resolvedCountriesPath: string | null = null
  let cachedSource: string | null = null

  return {
    name: "world-countries-filter",
    enforce: "pre",

    configResolved(config) {
      projectRoot = config.root
      resolvedCountriesPath =
        countriesJsonPath ?? locateCountriesJson(projectRoot)
    },

    resolveId(source) {
      if (source === REAL_SPECIFIER) return VIRTUAL_ID
      return null
    },

    async load(id) {
      if (id !== VIRTUAL_ID) return null

      if (cachedSource) return cachedSource

      if (!resolvedCountriesPath) {
        throw new Error(
          "[world-countries-filter] could not locate world-countries/countries.json. " +
            "Pass `countriesJsonPath` explicitly.",
        )
      }

      const fields = await resolveFields({
        mode,
        manualFields,
        include,
        projectRoot,
        plugin: this,
      })

      const raw = await fs.promises.readFile(resolvedCountriesPath, "utf8")
      const countries = JSON.parse(raw) as Record<string, unknown>[]

      const filtered = countries.map((entry) => {
        const out: Record<string, unknown> = {}
        for (const f of fields) {
          if (f in entry) out[f] = entry[f]
        }
        return out
      })

      // Pretty-print is wasteful for a generated module — minify the JSON to
      // squeeze every byte out of the chunk.
      const json = JSON.stringify(filtered)
      cachedSource = `// Generated by vite-plugin-world-countries-filter\n// Kept fields: ${fields.join(
        ", ",
      )}\nexport default ${json};\n`

      if (verbose) {
        const before = Buffer.byteLength(raw, "utf8")
        const after = Buffer.byteLength(json, "utf8")
        const pct = ((1 - after / before) * 100).toFixed(1)
        // eslint-disable-next-line no-console
        console.log(
          `[world-countries-filter] kept ${fields.length}/${WORLD_COUNTRIES_FIELDS.length} fields ` +
            `(${formatBytes(before)} → ${formatBytes(after)}, -${pct}%) [${mode}]`,
        )
      }

      return cachedSource
    },
  }
}

